// ntr-recomp: translates the ARM9 modules listed in a manifest into C++.
//
// Usage: ntr-recomp <manifest.tsv> <output dir>
//
// Output:
//   funcs.h            declarations of every recompiled function and HLE hook
//   <module>_<n>.cpp   translated functions, in chunks for parallel builds
//   registry.cpp       per-module function tables for runtime lookups
//   stats.txt          translation statistics
#include <cstdio>
#include <exception>
#include <filesystem>
#include <fstream>
#include <map>
#include <set>
#include <sstream>
#include <string>

#include "program.h"
#include "translator.h"

namespace fs = std::filesystem;
using namespace recomp;

namespace {

constexpr size_t kFunctionsPerChunk = 400;

// Rewrite a file only when its contents change, so rebuilds stay incremental.
void write_if_changed(const fs::path& path, const std::string& text) {
    std::ifstream in(path, std::ios::binary);
    if (in) {
        std::string old((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        if (old == text) return;
    }
    std::ofstream(path, std::ios::binary) << text;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 3) {
        std::fprintf(stderr, "usage: %s <manifest.tsv> <output dir>\n", argv[0]);
        return 2;
    }
    try {
        Program prog = load_program(argv[1]);
        fs::path out = argv[2];
        fs::create_directories(out);
        Stats stats;
        std::set<std::string> written;

        for (const auto& mod : prog.modules) {
            size_t chunk = 0;
            std::ostringstream body;
            size_t in_chunk = 0;
            auto flush = [&] {
                if (in_chunk == 0) return;
                std::string name = mod.name + "_" + std::to_string(chunk++) + ".cpp";
                write_if_changed(out / name, "// Generated by ntr-recomp. Do not edit.\n#include \"funcs.h\"\n\n" + body.str());
                written.insert(name);
                body.str("");
                in_chunk = 0;
            };
            for (const auto& fn : mod.functions) {
                body << Translator(prog, mod, fn, stats).translate();
                if (++in_chunk == kFunctionsPerChunk) flush();
            }
            flush();
        }

        std::ostringstream header;
        header << "// Generated by ntr-recomp. Do not edit.\n#pragma once\n#include <ntr/guest.h>\n\n";
        header << "namespace ntr {\n";
        for (const auto& id : stats.hle_ids) header << "void hle_" << id << "(Cpu& c, GuestFn orig);\n";
        header << "}  // namespace ntr\n\n";
        for (const auto& mod : prog.modules) {
            for (const auto& fn : mod.functions) {
                header << "void " << symbol_for(mod, fn) << "(ntr::Cpu& c);\n";
                if (!fn.hle.empty()) header << "void orig_" << symbol_for(mod, fn) << "(ntr::Cpu& c);\n";
            }
        }
        write_if_changed(out / "funcs.h", header.str());

        std::ostringstream reg;
        reg << "// Generated by ntr-recomp. Do not edit.\n#include \"funcs.h\"\n#include <ntr/registry.h>\n\n";
        reg << "namespace {\n";
        for (const auto& mod : prog.modules) {
            if (mod.functions.empty()) continue;
            reg << "const ntr::FuncEntry kFuncs_" << mod.name << "[] = {\n";
            for (const auto& fn : mod.functions) {
                reg << "    {" << hex32(fn.addr) << ", " << (fn.thumb ? 1 : 0) << ", &" << symbol_for(mod, fn) << "},\n";
            }
            reg << "};\n";
        }
        reg << "}  // namespace\n\nconst ntr::ModuleEntry ntr::kRecompModules[] = {\n";
        size_t count = 0;
        for (const auto& mod : prog.modules) {
            if (mod.functions.empty()) continue;
            reg << "    {\"" << mod.name << "\", " << hex32(mod.base) << ", " << hex32(uint32_t(mod.data.size()))
                << ", kFuncs_" << mod.name << ", " << mod.functions.size() << "},\n";
            count++;
        }
        reg << "};\nconst uint32_t ntr::kRecompModuleCount = " << count << ";\n";
        write_if_changed(out / "registry.cpp", reg.str());
        written.insert("registry.cpp");

        // Drop chunks left over from a previous run with more functions.
        for (const auto& entry : fs::directory_iterator(out)) {
            auto name = entry.path().filename().string();
            if (entry.path().extension() == ".cpp" && !written.count(name)) fs::remove(entry.path());
        }

        std::ostringstream st;
        st << "functions " << stats.functions << "\ninstructions " << stats.instructions << "\nunhandled "
           << stats.unhandled << "\nhle " << stats.hle_ids.size() << "\n";
        for (const auto& [kind, n] : stats.unhandled_kinds) st << "  " << n << "  " << kind << "\n";
        write_if_changed(out / "stats.txt", st.str());
        std::fputs(st.str().c_str(), stdout);
    } catch (const std::exception& e) {
        std::fprintf(stderr, "error: %s\n", e.what());
        return 1;
    }
    return 0;
}
